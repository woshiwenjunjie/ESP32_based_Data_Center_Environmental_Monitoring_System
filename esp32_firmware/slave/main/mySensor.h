/**
 * ============================================================
 *  mySensor - 传感器驱动模块（从机版）
 * ============================================================
 * 
 * 【硬件连接说明】
 * 
 * 本模块驱动以下传感器，请按以下方式连接：
 * 
 * ┌─────────────────────────────────────────────────────────────┐
 * │  DHT11/DHT22 温湿度传感器                                    │
 * ├─────────────────────────────────────────────────────────────┤
 * │  引脚    连接至                                              │
 * │  VCC    → 3.3V 或 5V                                        │
 * │  GND    → GND                                               │
 * │  DATA   → GPIO21 (DHTPIN)                                   │
 * │  NC     → 悬空（如为4针版本，NC引脚可不接）                    │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * ┌─────────────────────────────────────────────────────────────┐
 * │  MQ-2 烟雾/气体传感器                                        │
 * ├─────────────────────────────────────────────────────────────┤
 * │  引脚    连接至                                              │
 * │  VCC    → 5V (必须5V，3.3V加热不足)                          │
 * │  GND    → GND                                               │
 * │  AO     → GPIO36 (MQ2_AO) - 模拟输出                         │
 * │  DO     → GPIO16 (MQ2_DO) - 数字输出（阈值可调）              │
 * └─────────────────────────────────────────────────────────────┘
 * │  【重要提示】                                                 │
 * │  1. MQ-2需要预热1-2分钟才能达到稳定状态                       │
 * │  2. 首次上电后数值会波动，属正常现象                          │
 * │  3. 可通过模块上的电位器调节数字输出阈值                        │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * ┌─────────────────────────────────────────────────────────────┐
 * │  水位传感器（模拟式）                                         │
 * ├─────────────────────────────────────────────────────────────┤
 * │  引脚    连接至                                              │
 * │  VCC    → 3.3V 或 5V                                        │
 * │  GND    → GND                                               │
 * │  AO     → GPIO32 (WATERPIN) - 模拟输出                       │
 * └─────────────────────────────────────────────────────────────┘
 * │  【使用说明】                                                 │
 * │  1. 传感器有多个检测点，水位越高输出值越大                      │
 * │  2. 完全干燥时输出接近0，完全浸入时输出接近4095                │
 * │  3. 可根据实际应用场景校准水位与ADC值的对应关系                 │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 【依赖库】
 * - DHT sensor library by Adafruit
 * - Adafruit Unified Sensor
 * 
 * 安装方法：Arduino IDE → 工具 → 管理库 → 搜索安装
 */

#ifndef _MYSENSOR_H
#define _MYSENSOR_H

#include <Arduino.h>

// 避免 sensor_t 结构体冲突（与esp_camera.h兼容）
#define sensor_t adafruit_sensor_t
#include <DHT.h>
#include <Adafruit_Sensor.h>
#undef sensor_t

// ==================== 引脚定义 ====================
#define WATERPIN 32           // 水位传感器引脚 - 模拟输入
#define DHTPIN 21             // DHT传感器数据引脚 - 数字输入
#define DHTTYPE DHT11        // 传感器类型 (DHT11/DHT22) - 根据实际硬件修改
#define MQ2_AO 36            // MQ2模拟输出引脚 - ADC输入
#define MQ2_DO 16            // MQ2数字输出引脚 - 数字输入（带阈值比较）

extern DHT dht;

/**
 * 初始化所有传感器
 * - 初始化DHT温湿度传感器
 * - 配置MQ-2和水位的引脚模式
 * - 串口输出初始化状态
 */
void Sensor_init();

/**
 * 读取DHT温湿度传感器
 * @param temp 输出参数 - 温度值(°C)
 * @param humi 输出参数 - 湿度值(%RH)
 * 
 * 【注意事项】
 * - 两次读取间隔建议大于2秒，否则可能返回错误值
 * - 如果返回NaN，表示读取失败（检查接线或传感器是否损坏）
 */
void readmyDHT(float &temp, float &humi);

/**
 * 读取MQ-2烟雾/气体传感器
 * @param smoke 输出参数 - 烟雾状态(1=正常, 0=报警)
 * @param gas 输出参数 - 气体浓度ADC值(0-4095)
 * 
 * 【说明】
 * - smoke: 数字输出，超过阈值时变为0（报警）
 * - gas: 模拟输出，数值越大表示气体浓度越高
 * - 阈值可通过MQ-2模块上的电位器调节
 */
void readMQ2(int &smoke, int &gas);

/**
 * 读取水位传感器
 * @param water 输出参数 - 水位ADC值(0-4095)
 * 
 * 【说明】
 * - 0: 完全干燥
 * - 4095: 完全浸入水中
 * - 中间值表示不同水位高度
 */
void readwater(int &water);

#endif // _MYSENSOR_H
