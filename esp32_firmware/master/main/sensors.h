/**
 * ============================================================
 *  传感器数据采集模块 - 头文件（主机版）
 * ============================================================
 * 
 * 【硬件说明】
 * 
 * 本模块用于主机端的传感器数据采集，主机可选配以下传感器：
 * 
 * 1. DHT11/DHT22 温湿度传感器（可选）
 *    - 如果主机需要独立采集温湿度数据，可连接此传感器
 *    - 连接方式：数据引脚 → 指定GPIO, VCC → 3.3V/5V, GND → GND
 *    - 注意：主机主要通过TCP接收从机传感器数据，本地传感器为可选备份
 * 
 * 2. MQ-2 烟雾/气体传感器（可选）
 *    - 模拟输入，测量范围 0-4095
 *    - 可作为从机MQ-2数据的备份或独立监测点
 * 
 * 3. 水位传感器（可选）
 *    - 模拟输入，测量水位高度
 *    - ADC值转换为毫米：使用 analogToMm() 函数
 * 
 * 【与从机的区别】
 * - 从机：必须连接传感器，负责主要数据采集
 * - 主机：传感器可选，主要用于接收从机数据，本地传感器作为备份
 * 
 * 【数据流向】
 * 主机本地传感器 → SensorData结构体 → 与从机数据融合 → Web展示
 */

#ifndef SENSORS_H
#define SENSORS_H

#include <Arduino.h>

/**
 * 传感器数据结构体
 * 包含所有传感器的数据字段
 */
struct SensorData {
    float temperature;    // 温度 (°C) - 来自DHT传感器
    float humidity;       // 湿度 (%RH) - 来自DHT传感器
    int mq2;             // MQ-2气体浓度 (ADC值 0-4095)
    float water_level;   // 水位高度 (mm) - 经ADC转换后的实际高度
};

/**
 * 初始化传感器模块
 * - 配置传感器引脚
 * - 初始化DHT传感器（如已连接）
 * - 设置ADC分辨率（默认12位，0-4095）
 */
void initSensors();

/**
 * 读取所有传感器数据
 * @return SensorData结构体，包含当前所有传感器读数
 * 
 * 【使用说明】
 * - 如果传感器未连接，可能返回0或无效值
 * - 建议在调用前确认传感器已正确连接
 * - 读取间隔建议大于1秒，避免传感器响应不及时
 */
SensorData readSensors();

/**
 * 将ADC值转换为水位高度（毫米）
 * @param adc_value ADC原始值 (0-4095)
 * @return 水位高度 (mm)
 * 
 * 【转换公式】
 * 根据传感器特性和安装高度进行线性转换
 * 默认假设：0 = 0mm, 4095 = 最大量程
 * 可根据实际校准数据调整转换公式
 * 
 * 【示例】
 * int adc = analogRead(WATER_PIN);
 * float mm = analogToMm(adc);
 * Serial.printf("水位: %.1f mm\n", mm);
 */
float analogToMm(int adc_value);

#endif // SENSORS_H
